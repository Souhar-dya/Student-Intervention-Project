from __future__ import annotations

from dataclasses import dataclass
from typing import Any, TypedDict

from student_success_assistant.application.agent_tools import AdvisorToolRuntime
from student_success_assistant.application.llm_client import get_chat_llm
from student_success_assistant.core.config import get_settings
from student_success_assistant.infrastructure.student_repository import StudentRepository
from student_success_assistant.schemas.prediction import PredictionResponse
from student_success_assistant.schemas.recommendation import RecommendationResponse
from student_success_assistant.schemas.retrieval import RetrievedCase

SYSTEM_SCORE_COMPONENTS = {"base_risk", "score_cap", "score_floor"}


@dataclass(frozen=True)
class GroundingContext:
    query: str
    prediction: PredictionResponse
    retrieved_cases: list[RetrievedCase]
    student_profile_summary: str
    baseline_recommendation: str
    baseline_reasoning: str


class AdvisorGraphState(TypedDict, total=False):
    query: str
    prediction: PredictionResponse
    retrieved_cases: list[RetrievedCase]
    student_profile_summary: str
    evidence_case_ids: list[str]
    tool_outputs: list[dict[str, str]]
    recommendation: str
    reasoning: str


class AgentWorkflow:
    def __init__(
        self,
        repository: StudentRepository | None = None,
        tool_runtime: AdvisorToolRuntime | None = None,
    ) -> None:
        self._settings = get_settings()
        self._repository = repository or StudentRepository()
        self._tool_runtime = tool_runtime or AdvisorToolRuntime(self._repository)

    def generate_recommendation(
        self,
        *,
        student_id: str | None,
        evidence_case_ids: list[str],
        context: GroundingContext,
    ) -> RecommendationResponse | None:
        graph_response = self._generate_with_langgraph(
            student_id=student_id,
            evidence_case_ids=evidence_case_ids,
            context=context,
        )
        if graph_response is not None:
            return graph_response

        return self._generate_with_direct_llm(
            student_id=student_id,
            evidence_case_ids=evidence_case_ids,
            context=context,
        )

    def _generate_with_langgraph(
        self,
        *,
        student_id: str | None,
        evidence_case_ids: list[str],
        context: GroundingContext,
    ) -> RecommendationResponse | None:
        try:
            from langgraph.graph import END, StateGraph
        except ImportError:
            return None

        graph = StateGraph(AdvisorGraphState)
        graph.add_node("retrieve", self._retrieval_agent)
        graph.add_node("predict", self._prediction_agent)
        graph.add_node("recommend", self._recommendation_agent)
        graph.add_node("explain", self._explanation_agent)
        graph.set_entry_point("retrieve")
        graph.add_edge("retrieve", "predict")
        graph.add_edge("predict", "recommend")
        graph.add_edge("recommend", "explain")
        graph.add_edge("explain", END)
        compiled_graph = graph.compile()

        final_state = compiled_graph.invoke(
            {
                "query": context.query,
                "prediction": context.prediction,
                "retrieved_cases": context.retrieved_cases,
                "student_profile_summary": context.student_profile_summary,
                "evidence_case_ids": evidence_case_ids,
                "tool_outputs": [],
                "recommendation": context.baseline_recommendation,
                "reasoning": context.baseline_reasoning,
            }
        )
        recommendation = str(final_state.get("recommendation") or "").strip()
        if not recommendation:
            return None

        return RecommendationResponse(
            student_id=student_id,
            risk_category=context.prediction.risk_category,
            recommendation=recommendation,
            reasoning=str(final_state.get("reasoning") or "Generated by LangGraph advisor workflow."),
            evidence_case_ids=evidence_case_ids,
        )

    def _retrieval_agent(self, state: AdvisorGraphState) -> AdvisorGraphState:
        result = self._tool_runtime.summarize_retrieved_cases(state.get("retrieved_cases", []))
        return self._append_tool_output(state, result.name, result.output)

    def _prediction_agent(self, state: AdvisorGraphState) -> AdvisorGraphState:
        result = self._tool_runtime.summarize_prediction(state["prediction"])
        return self._append_tool_output(state, result.name, result.output)

    def _recommendation_agent(self, state: AdvisorGraphState) -> AdvisorGraphState:
        draft = self._tool_runtime.draft_intervention(
            state["prediction"],
            state.get("retrieved_cases", []),
        )
        feedback = self._tool_runtime.retrieve_feedback_examples(
            limit=self._settings.feedback_examples_limit,
        )
        judge_examples = self._tool_runtime.retrieve_judge_examples(
            limit=self._settings.feedback_examples_limit,
        )
        next_state = self._append_tool_output(state, draft.name, draft.output)
        next_state = self._append_tool_output(next_state, feedback.name, feedback.output)
        next_state = self._append_tool_output(next_state, judge_examples.name, judge_examples.output)

        llm_recommendation = self._call_llm(next_state)
        next_state["recommendation"] = llm_recommendation or draft.output
        next_state["reasoning"] = (
            "Generated by LangGraph workflow using retrieval, prediction, recommendation, "
            "and explanation agents."
        )
        return next_state

    def _explanation_agent(self, state: AdvisorGraphState) -> AdvisorGraphState:
        student_drivers = [
            item
            for item in state["prediction"].top_contributors
            if item.feature not in SYSTEM_SCORE_COMPONENTS
        ]
        student_drivers.sort(key=lambda item: abs(item.contribution), reverse=True)
        contributors = ", ".join(
            f"{item.feature} {item.contribution:+.2f}"
            for item in student_drivers[:3]
        )
        return self._append_tool_output(state, "explain_prediction", contributors)

    @staticmethod
    def _append_tool_output(state: AdvisorGraphState, name: str, output: str) -> AdvisorGraphState:
        tool_outputs = [*state.get("tool_outputs", []), {"name": name, "output": output}]
        return {**state, "tool_outputs": tool_outputs}

    def _generate_with_direct_llm(
        self,
        *,
        student_id: str | None,
        evidence_case_ids: list[str],
        context: GroundingContext,
    ) -> RecommendationResponse | None:
        content = self._call_llm(
            {
                "query": context.query,
                "prediction": context.prediction,
                "retrieved_cases": context.retrieved_cases,
                "student_profile_summary": context.student_profile_summary,
                "evidence_case_ids": evidence_case_ids,
                "tool_outputs": [
                    {
                        "name": "baseline_recommendation",
                        "output": context.baseline_recommendation,
                    },
                    {
                        "name": "retrieve_feedback_examples",
                        "output": self._tool_runtime.retrieve_feedback_examples(
                            limit=self._settings.feedback_examples_limit,
                        ).output,
                    },
                    {
                        "name": "retrieve_judge_examples",
                        "output": self._tool_runtime.retrieve_judge_examples(
                            limit=self._settings.feedback_examples_limit,
                        ).output,
                    },
                ],
            }
        )
        if not content:
            return None

        return RecommendationResponse(
            student_id=student_id,
            risk_category=context.prediction.risk_category,
            recommendation=content,
            reasoning="Generated by configured LLM using advisor tool context.",
            evidence_case_ids=evidence_case_ids,
        )

    def _call_llm(self, state: AdvisorGraphState | dict[str, Any]) -> str | None:
        llm = get_chat_llm(max_tokens=600)
        if llm is None:
            return None

        prediction = state["prediction"]
        retrieved_cases = state.get("retrieved_cases", [])
        tool_outputs = state.get("tool_outputs", [])
        evidence = (
            "\n".join(f"- {case.case_text}" for case in retrieved_cases[:3])
            or "- No cases retrieved."
        )
        tools = "\n".join(
            f"- {item['name']}: {item['output']}" for item in tool_outputs
        ) or "- No tool outputs."
        student_profile = state.get('student_profile_summary', 'not provided')
        prompt = (
            "You are an academic advisor assistant. Analyze the student's data and output "
            "a concise 3-5 sentence recommendation covering: root causes (with numbers), "
            "one immediate action (next 7 days), and a support plan (2-3 actions with "
            "WHO/WHAT/METRIC).\n\n"
            "Grading: final out of 20, pass at 10/20.\n"
            f"Risk: {prediction.risk_category}. "
            "Match intensity: High = daily/weekly, Medium = weekly/biweekly, Low = monthly.\n"
            "Be specific with numbers. No bullet lists, no section headers — just plain "
            "paragraphs.\n\n"
            f"Query: {state['query']}\n"
            f"Current student: {student_profile}\n"
            f"Risk category: {prediction.risk_category}\n"
            f"Risk score: {prediction.risk_score}\n"
            f"Retrieved evidence:\n{evidence}\n\n"
            f"Tool outputs:\n{tools}\n\n"
            "Return concise advisor-facing text."
        )
        try:
            response = llm.invoke(prompt)
        except Exception:
            return None
        content = str(response.content).strip()
        if not content:
            return None

        return content

    def graph_available(self) -> bool:
        try:
            from langgraph.graph import StateGraph
        except ImportError:
            return False
        return StateGraph is not None
